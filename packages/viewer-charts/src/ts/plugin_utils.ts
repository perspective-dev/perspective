import type { NativeUtils } from "@perspective-dev/viewer";

let UTILS: NativeUtils | undefined;

/** Supply the viewer's wasm module as the shared plugin code where no `<perspective-viewer>` class exists, as in a `Worker`. */
export function bind_plugin_utils(utils: NativeUtils): void {
    UTILS = utils;
}

/** The part of the code `<perspective-viewer>` shares with its plugins that also runs in a `Worker`. */
export function plugin_utils(): NativeUtils {
    UTILS ??= customElements.get("perspective-viewer").plugin_utils;
    return UTILS;
}
