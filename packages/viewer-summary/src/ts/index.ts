import { HTMLPerspectiveViewerSummaryPluginElement } from "./summary.ts";

interface PerspectiveViewerConstructor {
    registerPlugin(tagName: string): void;
}

async function _register_element(): Promise<void> {
    if (customElements.get("perspective-viewer-summary")) {
        console.warn(
            'Custom element "perspective-viewer-summary" is already registered; skipping duplicate registration (Perspective was loaded more than once on this page).',
        );
        return;
    }

    customElements.define(
        "perspective-viewer-summary",
        HTMLPerspectiveViewerSummaryPluginElement,
    );

    await customElements.whenDefined("perspective-viewer");
    const PerspectiveViewer = customElements.get(
        "perspective-viewer",
    ) as unknown as PerspectiveViewerConstructor;
    PerspectiveViewer.registerPlugin("perspective-viewer-summary");
}

_register_element();

export { HTMLPerspectiveViewerSummaryPluginElement };
export type {
    Breakdown,
    ColumnConfig,
    LabelPosition,
    SummaryPluginConfig,
    ValueFit,
} from "./types.ts";
