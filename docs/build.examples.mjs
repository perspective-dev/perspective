import * as fs from "node:fs";
import * as path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const EXAMPLES = path.resolve(__dirname, "../examples");
const DIST = path.join(__dirname, "dist/examples");

/**
 * The `examples/` projects which run entirely in the browser, each mapped to
 * the `package.json` script which builds its `dist/`.
 */
const HOSTED = {
    "esbuild-example": "build",
    "esbuild-duckdb-virtual": "build",
    "esbuild-minesweeper": "build",
    "react-example": "build",
    "trading-terminal": "build",
    "vite-example": "build",
    "webpack-example": "webpack_build",
};

fs.rmSync(DIST, { recursive: true, force: true });
for (const [name, script] of Object.entries(HOSTED)) {
    const root = path.join(EXAMPLES, name);
    const dist = path.join(root, "dist");
    fs.rmSync(dist, { recursive: true, force: true });
    execFileSync("pnpm", ["run", script], { cwd: root, stdio: "inherit" });
    fs.cpSync(dist, path.join(DIST, name), { recursive: true });
    console.log(`Hosted examples/${name} at /examples/${name}/`);
}
