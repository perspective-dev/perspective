import type { Page } from "@playwright/test";

export const TABLE = "load-viewer-csv";

export async function ready({ page }: { page: Page }) {
    await page.goto("/rust/perspective-viewer/test/html/superstore.html");
    await page.evaluate(async () => {
        while (!window["__TEST_PERSPECTIVE_READY__"]) {
            await new Promise((x) => setTimeout(x, 10));
        }
    });

    await page.evaluate(async () => {
        const viewer = document.querySelector("perspective-viewer")! as any;
        await viewer.restore({ plugin: "Debug", settings: true });
    });
}

export async function toggle(page: Page, force?: boolean) {
    await page.evaluate(async (force) => {
        const viewer = document.querySelector("perspective-viewer")! as any;
        await viewer.toggleWorkspaceConfig(force);
    }, force);
}

export async function saveWorkspace(page: Page): Promise<any> {
    return await page.evaluate(async () => {
        const viewer = document.querySelector("perspective-viewer")! as any;
        return await viewer.saveWorkspace();
    });
}

export async function iconRect(page: Page) {
    return await page
        .locator("perspective-viewer #status_reconnect")
        .evaluate((elem) => {
            const rect = elem.getBoundingClientRect();
            return {
                x: rect.x,
                y: rect.y,
                width: rect.width,
                height: rect.height,
            };
        });
}
