import type { ColorRecord, GradientStopRgb } from "../color.ts";

/** The model fields the body cell style handlers read. */
export interface CellStyleModel {
    _plugin_background: number[];
    _color: ColorRecord;
    _pos_fg_color: ColorRecord;
    _neg_fg_color: ColorRecord;
    _pos_bg_color: ColorRecord;
    _neg_bg_color: ColorRecord;
    _default_bg_color_stops: GradientStopRgb[];
    _series_palette: string[];
    _series_color_map: Map<string, Map<string, number>>;
    _series_color_seed: Map<string, number>;
    _ids: unknown[][];
    _column_paths: string[];
    _is_old_viewport?: boolean;
    last_meta?: unknown[][];
    last_reverse_ids?: Map<string, number>;
    last_reverse_columns?: Map<string, number>;
    _config: { split_by: string[] };
}

/** The cell metadata fields the date, datetime and boolean handlers read. */
export interface CellStyleMeta {
    _is_hidden_by_aggregate_depth?: boolean;
    user?: unknown;
}

/** The cell metadata fields the pulse handler reads. */
export interface CellFlashMeta {
    x: number;
    dy?: number;
    user?: unknown;
}
