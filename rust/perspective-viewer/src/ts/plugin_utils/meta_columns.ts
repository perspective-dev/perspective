/**
 * The metadata column names, `__ROW_PATH__`, `__ROW_PATH_<n>__`, `__ID__` and
 * `__GROUPING_ID__`.
 */
const META_COLUMN_RE = /^__(?:ROW_PATH(?:_\d+)?|ID|GROUPING_ID)__$/;

export function isMetaColumn(name: string): boolean {
    return META_COLUMN_RE.test(name);
}
