use perspective_js::utils::ApiResult;

use crate::components::viewer::PerspectiveViewerMsg;
use crate::config::ViewerConfigInitial;
use crate::session::MissingTable;
use crate::tasks::{WorkspaceHost, create_panel};
use crate::workspace::PanelId;

/// Add a panel on `table` of `client` and make it the active panel.
pub(crate) async fn create_table_panel(
    host: &WorkspaceHost,
    client: perspective_client::Client,
    table: String,
) -> ApiResult<PanelId> {
    let notify = host
        .dispatch
        .reform(|()| PerspectiveViewerMsg::LayoutChanged);

    let id = create_panel(
        &host.elem,
        &host.presentation,
        &host.workspace,
        &notify,
        None,
        ViewerConfigInitial::new(table),
        Some(client),
        MissingTable::Error,
    )
    .await?;

    host.dispatch
        .emit(PerspectiveViewerMsg::SetActivePanel(id.to_string(), None));

    Ok(id)
}
