//! The settings-sidebar placeholder shown in place of a tab body that has
//! nothing to show while the element is an EMPTY STAGE (zero panels): the
//! Query, Plugin and Debug tabs all read a panel's table/plugin/config.

use yew::prelude::*;

/// A "No table loaded" message filling a settings tab body. The label is the
/// localizable `--psp-label--no-table--content` (see `themes/intl.css`),
/// rendered by `viewer.css` `.psp-empty-placeholder::before`.
#[function_component]
pub fn EmptyPlaceholder() -> Html {
    html! { <div class="sidebar_column psp-empty-placeholder" /> }
}
