def joined_column_paths(view, **window):
    """A View's column paths as "|"-joined strings.

    For the many tests whose subject is which columns exist in what order
    rather than the typed values `column_paths` now returns. Tests of
    `column_paths` itself assert the area directly - this helper is
    deliberately lossy in the same way the old wire format was, so it must
    not be used to pin a split value's type or rendering.
    """
    area = view.column_paths(**window)
    width = len(area[-1]) if area else 0
    out = []
    for x in range(width):
        parts = [
            str(area[level][x])
            for level in range(len(area))
            if area[level][x] is not None
        ]
        out.append("|".join(parts))
    return out
