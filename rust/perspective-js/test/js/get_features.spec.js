import { test, expect } from "@perspective-dev/test";
import perspective from "./perspective_client";

test("get_features() reports the native engine's features", async () => {
    const table = await perspective.table({ x: [1, 2, 3] });
    const features = await table.get_features();
    expect(features.group_by).toBe(true);
    expect(features.split_by).toBe(true);
    expect(features.expand_collapse).toBe(true);
    expect(features.update).toBe(true);
    expect(features.group_rollup_mode).toEqual(
        expect.arrayContaining(["rollup", "flat", "total"]),
    );
    expect(Object.keys(features.aggregates)).toContain("integer");
    await table.delete();
});
