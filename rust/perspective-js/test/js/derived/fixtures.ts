import perspective from "../perspective_client.ts";

export const SCHEMA = {
    id: "integer",
    g: "string",
    h: "string",
    s: "string",
    x: "float",
    y: "integer",
    w: "float",
};

export function rows(n: number, offset = 0) {
    const G = ["a", "b", "c"];
    const H = ["p", "q"];
    const S = ["Mon", "Tue", "Wed"];
    const out = [];
    for (let i = offset; i < offset + n; i++) {
        out.push({
            id: i,
            g: G[i % G.length],
            h: H[i % H.length],
            s: S[Math.floor(i / 3) % S.length],
            x: i * 1.5 + 1,
            y: (i * 7) % 11,
            w: (i % 4) + 1,
        });
    }

    return out;
}

export async function make_source(n = 24) {
    const table = await perspective.table(SCHEMA, { index: "id" });
    await table.update(rows(n));
    return table;
}

