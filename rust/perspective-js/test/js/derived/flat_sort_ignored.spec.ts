import { test, expect } from "@perspective-dev/test";
import perspective from "../perspective_client.ts";
import { expect_flat_parity } from "./oracle.ts";
import { make_source, rows } from "./fixtures.ts";

test.describe("Derived table ignores a flat parent's sort", function () {
    test("order is the source's insertion order", async function () {
        const source = await make_source();
        const view = await source.view({ sort: [["x", "desc"]] });
        const derived = await perspective.table(view);
        const unsorted = await source.view();
        const child = await derived.view();
        expect(await child.to_json()).toEqual(await unsorted.to_json());
        await source.update(rows(4, 40));
        expect(await child.to_json()).toEqual(await unsorted.to_json());
        await expect_flat_parity(view, derived);
        await child.delete();
        await unsorted.delete();
        await derived.delete();
        await view.delete();
        await source.delete();
    });
});
