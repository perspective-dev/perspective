import { test, expect } from "@perspective-dev/test";
import { make_client } from "@perspective-dev/client";

test("A client rejects requests once its transport reports an error", async () => {
    let sent = 0;
    const client = make_client(async () => {
        sent++;
    });

    await client.handle_error("closed");
    await expect(client.get_hosted_table_names()).rejects.toThrow();
    expect(sent).toEqual(0);
});

test("A client fires `on_error` once per lost connection", async () => {
    let fired = 0;
    const client = make_client(async () => {});
    await client.on_error(() => {
        fired++;
    });

    await client.handle_error("closed");
    await client.handle_error("closed again");
    expect(fired).toEqual(1);
});
