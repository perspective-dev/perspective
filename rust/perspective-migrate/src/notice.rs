use serde::Serialize;
use serde_json::Value;

/// Information a migration could not carry into the current schema exactly.
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(tag = "kind")]
pub enum Notice {
    /// `value` at `pointer` has no current representation and was removed.
    Dropped {
        step: &'static str,
        pointer: String,
        value: Value,
    },

    /// The value at `pointer` was rewritten to the nearest current form.
    Approximated {
        step: &'static str,
        pointer: String,
        reason: &'static str,
    },
}
