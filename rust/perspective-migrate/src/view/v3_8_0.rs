use serde_json::{Map, Value};

use crate::error::MigrateError;
use crate::json::object_mut;
use crate::step::StepCx;

pub(super) fn multi_aggregate_args(
    view: &mut Map<String, Value>,
    _cx: &mut StepCx,
) -> Result<(), MigrateError> {
    let Some(aggregates) = object_mut(view, "aggregates") else {
        return Ok(());
    };

    for aggregate in aggregates.values_mut() {
        if let Value::Array(parts) = aggregate
            && let [_, arg @ Value::String(_)] = parts.as_mut_slice()
        {
            *arg = Value::Array(vec![arg.take()]);
        }
    }

    Ok(())
}
