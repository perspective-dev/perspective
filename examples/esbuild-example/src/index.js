import perspective from "@perspective-dev/client";
import perspective_viewer from "@perspective-dev/viewer";
import "@perspective-dev/viewer-datagrid";
import "@perspective-dev/viewer-charts";

import "@perspective-dev/viewer/dist/css/themes.css";
import "./index.css";

import arrow from "superstore-arrow/superstore.lz4.arrow";

import SERVER_WASM from "@perspective-dev/server/dist/wasm/perspective-server.wasm";
import CLIENT_WASM from "@perspective-dev/viewer/dist/wasm/perspective-viewer.wasm";

await perspective_viewer.init({
    server: fetch(SERVER_WASM),
    viewer: fetch(CLIENT_WASM),
});

const req = fetch(arrow);
const viewer = document.createElement("perspective-viewer");
document.body.append(viewer);
const worker = await perspective.worker();
const worker2 = await perspective.worker();
const resp = await req;
const buffer = await resp.arrayBuffer();
await worker.table(buffer, { name: "superstore1" });
await worker2.table(buffer, { name: "superstore2" });
viewer.load(worker);
viewer.load(worker2);

window.TEST = worker2;
